#!/usr/bin/env python3
"""Validate a product manifest and generate its firmware configuration.

Usage: gen_product.py products/<name>.json <output-dir>

Writes product_config.h and sdkconfig.product into the output directory.
With --check, validates only and writes nothing.
"""
import argparse
import json
import re
import sys
from pathlib import Path

# Pin map from the Seeed XIAO ESP32-C5 wiki. Pins not listed here are reserved:
# GPIO6/26 battery sensing, GPIO27 user LED, GPIO28 boot button.
BOARDS = {
    "xiao-esp32c5": {
        "target": "esp32c5",
        "pins": {
            "D0": 1, "D1": 0, "D2": 25, "D3": 7, "D4": 23, "D5": 24,
            "D6": 11, "D7": 12, "D8": 8, "D9": 9, "D10": 10,
        },
    },
}
ROLES = {"router", "sleepy"}
ENDPOINTS = {
    # type: (C enum value, roles allowed)
    "on_off_plugin_unit": ("PRODUCT_EP_ON_OFF_PLUGIN_UNIT", {"router"}),
    "generic_switch": ("PRODUCT_EP_GENERIC_SWITCH", {"router", "sleepy"}),
}
TEST_VENDOR_IDS = range(0xFFF1, 0xFFF5)
TEST_DAC_PRODUCT_IDS = range(0x8000, 0x8064)


class ManifestError(Exception):
    pass


def validate(manifest):
    errors = []
    for key in ("name", "board", "role", "vendor_id", "product_id", "endpoints"):
        if key not in manifest:
            errors.append(f"missing required field '{key}'")
    if errors:
        raise ManifestError("; ".join(errors))

    board = BOARDS.get(manifest["board"])
    if board is None:
        errors.append(f"unknown board '{manifest['board']}'")
    role = manifest["role"]
    if role not in ROLES:
        errors.append(f"unknown role '{role}' (expected one of {sorted(ROLES)})")

    vendor_id = int(manifest["vendor_id"], 16)
    product_id = int(manifest["product_id"], 16)
    if vendor_id in TEST_VENDOR_IDS and product_id not in TEST_DAC_PRODUCT_IDS:
        errors.append("test vendor IDs need a product_id from 0x8000 to 0x8063 to match the test certificates")

    if not manifest["endpoints"]:
        errors.append("a product needs at least one endpoint")
    used = {}
    for index, endpoint in enumerate(manifest["endpoints"]):
        where = f"endpoint {index}"
        spec = ENDPOINTS.get(endpoint.get("type"))
        if spec is None:
            errors.append(f"{where}: unknown type '{endpoint.get('type')}'")
        elif role in ROLES and role not in spec[1]:
            errors.append(f"{where}: '{endpoint['type']}' is not allowed on a {role} product")
        pin = endpoint.get("pin")
        if board is not None and pin not in board["pins"]:
            errors.append(f"{where}: pin '{pin}' is not available on {manifest['board']}")
        if pin in used:
            errors.append(f"{where}: pin '{pin}' is already used by endpoint {used[pin]}")
        used.setdefault(pin, index)
    if errors:
        raise ManifestError("; ".join(errors))


def render_header(manifest):
    pins = BOARDS[manifest["board"]]["pins"]
    rows = []
    for endpoint in manifest["endpoints"]:
        kind = ENDPOINTS[endpoint["type"]][0]
        low = "true" if endpoint.get("active_low") else "false"
        rows.append(f"    {{{kind}, {pins[endpoint['pin']]}, {low}}},")
    body = "\n".join(rows)
    return f"""/* Generated by tools/gen_product.py from {manifest['name']}.json. Do not edit. */
#pragma once

#include "product.h"

#define PRODUCT_NAME "{manifest['name']}"

static const product_endpoint_t kProductEndpoints[] = {{
{body}
}};
static const unsigned kProductEndpointCount = sizeof(kProductEndpoints) / sizeof(kProductEndpoints[0]);
"""


def render_sdkconfig(manifest):
    """The Matter product name is not a Kconfig option on ESP32: it comes from
    the factory data partition, so it is not set here."""
    target = BOARDS[manifest["board"]]["target"]
    return (
        f'CONFIG_IDF_TARGET="{target}"\n'
        f"CONFIG_DEVICE_VENDOR_ID={manifest['vendor_id']}\n"
        f"CONFIG_DEVICE_PRODUCT_ID={manifest['product_id']}\n"
    )


def version_number(version):
    """Maps 1.2.3 to the Matter software version. OTA only accepts a higher number."""
    match = re.fullmatch(r"(\d+)\.(\d{1,3})\.(\d{1,3})(-[0-9A-Za-z.-]+)?", version)
    if match is None:
        raise ManifestError(f"version '{version}' is not MAJOR.MINOR.PATCH with MINOR and PATCH under 1000")
    major, minor, patch = (int(part) for part in match.groups()[:3])
    return major * 1_000_000 + minor * 1_000 + patch


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output", type=Path, nargs="?")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--print-role", action="store_true")
    parser.add_argument("--version-number", metavar="VERSION", help="print the Matter software version for VERSION")
    args = parser.parse_args()

    if args.version_number:
        try:
            print(version_number(args.version_number))
        except ManifestError as error:
            sys.exit(str(error))
        return

    manifest = json.loads(args.manifest.read_text())
    try:
        validate(manifest)
    except ManifestError as error:
        sys.exit(f"{args.manifest}: {error}")

    if args.print_role:
        print(manifest["role"])
    if args.check or args.print_role:
        return
    if args.output is None:
        parser.error("output directory is required unless --check is used")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "product_config.h").write_text(render_header(manifest))
    (args.output / "sdkconfig.product").write_text(render_sdkconfig(manifest))


if __name__ == "__main__":
    main()
